    with contextlib.redirect_stdout(buf):
        try:
            st.main()
        except SystemExit:
            pass
    suite = [l for l in buf.getvalue().splitlines() if "checks" in l]

    print("1. INTERNAL CENSUS -- every corpus the suite exercises")
    print(f"   suite: {suite[-1] if suite else '(no count)'}")
    a = _tally["authored"]
    print(f"   machines {_tally['machines']}   rules {_tally['rules']}   "
          f"bundled {_tally['bundled']}   authored {a}")
    if a:
        print(f"   GENERIC {_tally['generic']} ({100*_tally['generic']/a:.1f}%)   "
              f"ground {_tally['ground']} ({100*_tally['ground']/a:.1f}%)")
        print(f"   shapes: {len(_fine)} fine, {len(_coarse)} coarse, "
              f"{len(_coarsest)} coarsest")
        for k in (1, 3, 5, 10):
            cov = sum(n for _, n in _fine.most_common(k))
            print(f"      top {k:2} fine shapes cover {100*cov/a:5.1f}%")
        print("   the two PRIMITIVES, as a share of authored rules:")
        prim = 0
        for s, n in _coarse.most_common(2):
            prim += n
            print(f"      {n:5} {100*n/a:5.1f}%  {s}")
        print(f"      {prim:5} {100*prim/a:5.1f}%  together")
    print()
    _external()
    print()
    bad = _probe()
    print()
    bad += _composition()
    print()
    print(f"{len(PROBES)+1} expressibility probes, 3 composition checks, "
          f"{bad} changed")
    return 0


